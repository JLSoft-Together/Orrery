// Split button opens a menu: the new pane runs the picked agent (or a browser) in the same folder.
const { launch, OUT } = require('./cdp.cjs')
const S = `document.querySelector('#app').__vue_app__.config.globalProperties.$pinia._s`
const W = `${S}.get('workspace')`
const results = []
const check = (name, ok, extra = '') => { results.push(`${ok ? 'PASS' : 'FAIL'} ${name}${extra ? ' — ' + extra : ''}`); console.log(results.at(-1)) }

;(async () => {
  const app = await launch(process.argv[2] ? { exe: process.argv[2] } : {})
  const { evaluate, waitFor, shot, sleep, cmd, key } = app
  try {
    await waitFor(`!!window.ccmDesktop && !!${S}.get('ui')`, 30000, 'app ready')
    await evaluate(`localStorage.setItem('ccm.tourDone','1'); localStorage.setItem('ccm.locale','en'); localStorage.setItem('ccm.whatsNew.seen','${require('../package.json').version}'); localStorage.setItem('ccm.setupDone','1'); localStorage.setItem('ccm.tourWorkspaceDone','1'); localStorage.setItem('ccm.workspace.preset','shell')`)
    await cmd('Page.reload')
    await sleep(1500)
    await waitFor(`!!${S}.get('ui')`, 30000, 'reloaded')
    await evaluate(`${S}.get('ui').view = 'workspace'`)
    await waitFor(`!!document.querySelector('[data-launch-row]')`, 15000, 'picker')
    await evaluate(`[...document.querySelectorAll('[data-launch-row]')].at(-1).click()`)
    await waitFor(`${W}.panes[0]?.state === 'running'`, 20000, 'shell running')

    await evaluate(`document.querySelector('[data-pane-split]').click()`)
    await waitFor(`!!document.querySelector('[role=menu]')`, 5000, 'menu')
    const items = await evaluate(`[...document.querySelectorAll('[role=menu] [role=menuitem]')].map((b) => b.textContent.trim())`)
    check('menu lists Claude, Codex, Shell, Browser, Other project', items.length === 5 && /Claude/.test(items[0]) && /Codex/.test(items[1]) && /Shell/.test(items[2]) && /Browser/.test(items[3]) && /Other project/.test(items[4]), JSON.stringify(items))
    check('opened by mouse: the menu panel has focus, no item highlighted', await evaluate(`document.activeElement?.matches('[data-menu-panel]') === true`))
    await key('ArrowUp', 'ArrowUp', 38)
    check('↑ from the panel lands on the last item', await evaluate(`/Other project/.test(document.activeElement?.textContent ?? '') && document.activeElement?.getAttribute('role') === 'menuitem'`))
    await key('ArrowDown', 'ArrowDown', 40)
    check('arrows wrap through the items', await evaluate(`/Claude/.test(document.activeElement?.textContent ?? '')`))
    await shot('split-menu')
    await key('Escape', 'Escape', 27)
    check('Esc closes the menu', await evaluate(`!document.querySelector('[role=menu]')`))

    await evaluate(`document.querySelector('[data-pane-split]').click()`)
    await waitFor(`!!document.querySelector('[role=menu]')`, 5000, 'menu again')
    await evaluate(`[...document.querySelectorAll('[role=menu] [role=menuitem]')].find((b) => /Codex/.test(b.textContent)).click()`)
    await waitFor(`${W}.panes.length === 2`, 5000, 'second pane')
    const pair = await evaluate(`JSON.stringify(${W}.panes.map((p) => [p.preset, p.cwd]))`)
    const [a, b] = JSON.parse(pair)
    check('picked agent opens next to it, same folder', b[0] === 'codex' && a[1] === b[1], pair)
    check('still one tab', await evaluate(`${W}.tabs.length === 1`))
    await sleep(800)
    await shot('split-done')

    // --- v99 project groups: two projects side by side in one tab, each with its own splits ---
    const fs = require('node:fs')
    const os = require('node:os')
    const path = require('node:path')
    const BASE = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'ccm-e2e-groups-')))
    const P = path.join(BASE, 'alpha')
    const Q = path.join(BASE, 'beta')
    fs.mkdirSync(P)
    fs.mkdirSync(Q)
    const FRAMES = `[...document.querySelectorAll('[data-group-frame]')]`
    const frame = (dir) => `document.querySelector('[data-group-frame=' + JSON.stringify(${JSON.stringify(dir)}) + ']')`
    const p1 = JSON.stringify(await evaluate(`${W}.open('shell', ${JSON.stringify(P)}, undefined, { tab: true }).key`))
    await evaluate(`${W}.split(${p1}, 'col')`)
    await sleep(500)
    check('a single-project tab has no group frame', await evaluate(`${FRAMES}.length === 0`))
    await evaluate(`${W}.split(${p1}, 'row', { kind: 'term', preset: 'shell' }, { cwd: ${JSON.stringify(Q)} })`)
    await waitFor(`${FRAMES}.length === 2`, 5000, 'two group frames')
    const geo = JSON.parse(await evaluate(`JSON.stringify(${FRAMES}.map((el) => { const r = el.getBoundingClientRect(); return { p: el.dataset.groupFrame, l: r.left, r: r.right, t: r.top, b: r.bottom, name: el.querySelector('[data-group-name]')?.textContent.trim() } }))`))
    check('two project groups sit side by side, alpha left, beta right', geo.length === 2 && geo[0].name === 'alpha' && geo[1].name === 'beta' && geo[1].l >= geo[0].r - 1 && Math.abs(geo[0].t - geo[1].t) < 2, JSON.stringify(geo))
    const inside = await evaluate(`(() => { const f = ${frame(P)}.getBoundingClientRect(); const head = ${frame(P)}.querySelector('[data-group-head]').getBoundingClientRect(); return ${W}.tabOf(${p1}) && [...document.querySelectorAll('[data-pane]')].filter((el) => el.getBoundingClientRect().width > 0 && el.getBoundingClientRect().left < f.right - 2).every((el) => { const r = el.getBoundingClientRect(); return r.left >= f.left && r.right <= f.right + 1 && r.top >= head.bottom - 1 && r.bottom <= f.bottom + 1 }) })()`)
    check('alpha panes stay inside the alpha frame, below its header', inside)
    await evaluate(`${frame(Q)}.querySelector('[data-group-add]').click()`)
    await waitFor(`${W}.groupKeys(${W}.tabOf(${p1}).key, ${JSON.stringify(Q)}).length === 2`, 5000, 'beta split')
    check('+ in the beta header opens a session in beta', await evaluate(`${W}.panes.at(-1).cwd === ${JSON.stringify(Q)} && ${W}.groupKeys(${W}.tabOf(${p1}).key, ${JSON.stringify(P)}).length === 2`))
    check('panes of other groups show no per-pane project chip', await evaluate(`!document.querySelector('[data-pane-project]')`))
    await sleep(600)
    await shot('groups-01-side-by-side')

    const mouse = (type, p, buttons = 1) => cmd('Input.dispatchMouseEvent', { type, x: p.x, y: p.y, button: 'left', buttons, clickCount: type === 'mouseMoved' ? 0 : 1 })
    const from = await evaluate(`(() => { const r = ${frame(Q)}.querySelector('[data-group-head]').getBoundingClientRect(); return { x: r.left + r.width / 2, y: r.top + r.height / 2 } })()`)
    const to = await evaluate(`(() => { const r = ${frame(P)}.getBoundingClientRect(); return { x: r.left + 14, y: r.top + r.height / 2 } })()`)
    await mouse('mousePressed', from)
    for (let i = 1; i <= 12; i++) {
      await mouse('mouseMoved', { x: from.x + ((to.x - from.x) * i) / 12, y: from.y + ((to.y - from.y) * i) / 12 })
      await sleep(30)
    }
    await sleep(200)
    check('dragging a group header over the other group shows the left drop preview', await evaluate(`document.querySelector('[data-drop-preview]')?.dataset.edge === 'left'`))
    await shot('groups-02-drag')
    await mouse('mouseReleased', to, 0)
    await waitFor(`${FRAMES}[0]?.dataset.groupFrame === ${JSON.stringify(Q)}`, 5000, 'groups reordered')
    check('dropping the header moves beta before alpha', true)

    const MENU = `document.querySelector('[data-context-menu]')`
    const menuItem = (id) => `document.querySelector('[data-context-menu] [data-menu-id="${id}"]')`
    await evaluate(`(() => { const el = ${frame(Q)}.querySelector('[data-group-head]'); const r = el.getBoundingClientRect(); el.dispatchEvent(new MouseEvent('contextmenu', { bubbles: true, cancelable: true, clientX: r.left + 120, clientY: r.top + 10, button: 2 })); return true })()`)
    await waitFor(`!!${MENU}`, 5000, 'group menu')
    check('right-click on a group header offers rename, colour, collapse, move, close', await evaluate(`['rename', 'colour', 'fold', 'to-tab', 'close'].every((id) => !!document.querySelector('[data-context-menu] [data-menu-id="' + id + '"]'))`))
    await shot('groups-03-menu')
    await evaluate(`${menuItem('rename')}.click()`)
    await waitFor(`!!document.querySelector('[data-group-rename]')`, 5000, 'rename input')
    await evaluate(`(() => { const i = document.querySelector('[data-group-rename]'); i.value = 'API'; i.dispatchEvent(new Event('input')); i.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter', bubbles: true })) })()`)
    await waitFor(`${frame(Q)}.querySelector('[data-group-name]')?.textContent.trim() === 'API'`, 5000, 'renamed')
    check('Rename shows the new group name', true)
    await evaluate(`${W}.setGroupMeta(${W}.tabOf(${p1}).key, ${JSON.stringify(Q)}, { tone: 1 })`)
    await sleep(200)
    check('a picked colour replaces the automatic one', await evaluate(`${frame(Q)}.dataset.projectTone === '1'`))
    const before = await evaluate(`${frame(P)}.getBoundingClientRect().width`)
    await evaluate(`${W}.setGroupMeta(${W}.tabOf(${p1}).key, ${JSON.stringify(Q)}, { folded: true })`)
    await waitFor(`!!${frame(Q)}?.querySelector('[data-group-unfold]')`, 5000, 'folded')
    const strip = await evaluate(`${frame(Q)}.getBoundingClientRect().width`)
    const after = await evaluate(`${frame(P)}.getBoundingClientRect().width`)
    check('Collapse leaves a thin strip and the other group takes the space', strip < 60 && after > before + 200, `${strip} / ${before} → ${after}`)
    await shot('groups-04-collapsed')
    await evaluate(`${frame(Q)}.querySelector('[data-group-unfold]').click()`)
    await waitFor(`!${frame(Q)}.querySelector('[data-group-unfold]')`, 5000, 'unfolded')
    check('clicking the strip expands the group', true)
    const chord = async (k, code, vk, mods) => {
      await cmd('Input.dispatchKeyEvent', { type: 'rawKeyDown', key: k, code, windowsVirtualKeyCode: vk, modifiers: mods })
      await cmd('Input.dispatchKeyEvent', { type: 'keyUp', key: k, code, windowsVirtualKeyCode: vk, modifiers: mods })
      await sleep(300)
    }
    await evaluate(`${W}.activate(${W}.groupKeys(${W}.tabOf(${p1}).key, ${JSON.stringify(Q)})[0])`)
    await chord('ArrowRight', 'ArrowRight', 39, 2 | 1)
    check('Ctrl+Alt+→ focuses the group on the right', await evaluate(`${W}.groupKeys(${W}.tabOf(${p1}).key, ${JSON.stringify(P)}).includes(${W}.activeKey)`))
    await chord('ArrowLeft', 'ArrowLeft', 37, 2 | 1 | 8)
    check('Ctrl+Alt+Shift+← moves the focused group left', await evaluate(`${FRAMES}[0]?.dataset.groupFrame === ${JSON.stringify(P)}`))
    await chord('g', 'KeyG', 71, 2 | 1)
    await waitFor(`!!document.querySelector('[data-split-project]')`, 5000, 'add group picker')
    check('Ctrl+Alt+G opens the project picker for a new group', await evaluate(`/Add a project as a group/.test(document.querySelector('[data-split-project]').textContent)`))
    await key('Escape', 'Escape', 27)
    await sleep(300)

    const tabsBefore = await evaluate(`${W}.tabs.length`)
    await evaluate(`${frame(Q)}.querySelector('[data-group-to-tab]').click()`)
    await waitFor(`${W}.tabs.length === ${tabsBefore + 1}`, 5000, 'group to tab')
    check('Move to new tab takes beta out, its tab is beta', await evaluate(`${W}.activeTab.project === ${JSON.stringify(Q)} && ${W}.activeTab.root && !JSON.stringify(${W}.activeTab.root).includes('"group"')`))
    await evaluate(`${W}.activate(${p1})`)
    await sleep(400)
    check('alpha tab is a plain tab again, no frames', await evaluate(`${FRAMES}.length === 0`))
  } catch (e) {
    check('run', false, e.message)
    await shot('split-99-error').catch(() => {})
  } finally {
    app.stop()
    require('node:fs').writeFileSync(require('node:path').join(OUT, 'results-split.txt'), results.join('\n'))
    process.exit(0)
  }
})()
