for (const lang of ['en', 'vi']) {
  const out = { '@@locale': lang }
  for (const [key, v] of Object.entries(T)) {
    out[key] = v[lang]
    if (lang === 'en' && v.ph) {
      out[`@${key}`] = {
        placeholders: Object.fromEntries(Object.entries(v.ph).map(([n, t]) => [n, { type: t }])),
      }
    }
  }
  fs.writeFileSync(`lib/l10n/app_${lang}.arb`, JSON.stringify(out, null, 2) + '\n')
}
